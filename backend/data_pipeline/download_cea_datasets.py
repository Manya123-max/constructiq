def load_and_merge_datasets():
    print("[INFO] Merging official CEA government datasets...")
    
    synthetic_file = os.path.join(DATA_DIR, "synthetic_projects.json")
    if os.path.exists(synthetic_file):
        with open(synthetic_file, encoding="utf-8") as f:
            data = json.load(f)
    else:
        data = {"hydro": [], "thermal": [], "monitoring": {}}

    # Merge CEA projects
    hydro_combined = REAL_CEA_HYDRO + [h for h in data.get("hydro", []) if not h.get("project_id", "").startswith("CEA-")]
    thermal_combined = REAL_CEA_THERMAL + [t for t in data.get("thermal", []) if not t.get("project_id", "").startswith("CEA-")]

    output = {
        "hydro": hydro_combined,
        "thermal": thermal_combined,
        "monitoring": data.get("monitoring", {}),
    }

    with open(synthetic_file, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2)

    print(f"[OK] Total Hydro Projects: {len(hydro_combined)} ({len(REAL_CEA_HYDRO)} Official CEA)")
    print(f"[OK] Total Thermal Projects: {len(thermal_combined)} ({len(REAL_CEA_THERMAL)} Official CEA)")
    print(f"[OK] Dataset updated at {synthetic_file}")

if __name__ == "__main__":
    load_and_merge_datasets()
